// owner: U3 (parity tooling)
'use strict'
/** Render the assembled parity matrix (docs/parity.md) and differences (docs/differences.md). */
const path = require('path')
const { renderTable } = require('./markdown')
const { DIFF_LINK_RE } = require('./items')

const CATEGORY_ORDER = ['export', 'property', 'method', 'event', 'window', 'test', 'internal-test']
const CATEGORY_TITLES = {
  export: 'Module exports',
  property: 'Bot properties',
  method: 'Bot methods',
  event: 'Bot events',
  window: 'Window classes',
  test: 'mineflayer external tests',
  'internal-test': 'mineflayer internal tests (internalTest.js)'
}
const STATUS_COLUMNS = ['total', 'done', 'adapted', 'n.a.', 'todo']

/** Rewrite relative markdown links of a cell written in `fromDir` so they work from `toDir`. */
function relinkCell (text, fromDir, toDir) {
  return String(text).replace(/\]\(([^)\s]+)\)/g, (m, target) => {
    if (/^([a-z]+:|#|\/)/i.test(target)) return m
    const [p, hash] = target.split('#')
    const rel = path.relative(toDir, path.resolve(fromDir, p)).split(path.sep).join('/')
    return `](${rel}${hash ? '#' + hash : ''})`
  })
}

function pct (n, total) {
  return total ? `${Math.round((100 * n) / total)}%` : '–'
}

function summaryTable (title, buckets, sortKeys) {
  const keys = sortKeys(Object.keys(buckets))
  const rows = keys.map(k => {
    const b = buckets[k]
    const closed = b.done + b.adapted + b['n.a.']
    return [k, ...STATUS_COLUMNS.map(c => String(b[c])), pct(closed, b.total)]
  })
  return renderTable([title, ...STATUS_COLUMNS, 'closed'], rows)
}

const byUnit = (keys) => keys.sort((a, b) => unitOrder(a) - unitOrder(b))
const byCategory = (keys) => keys.sort((a, b) => idx(a) - idx(b))
/** 'U8' → 8; anything else last */
function unitOrder (unit) {
  const n = /^U(\d+)$/.exec(unit)
  return n ? Number(n[1]) : Infinity
}
function idx (c) {
  const i = CATEGORY_ORDER.indexOf(c)
  return i < 0 ? CATEGORY_ORDER.length : i
}

/**
 * @param {ReturnType<import('./assemble').assemble>} result
 * @param {{ repoRoot: string, outDir: string, reference?: object|null }} opts
 */
function renderParity (result, { repoRoot, outDir, reference = null }) {
  const errors = result.problems.filter(p => p.level === 'error')
  const warnings = result.problems.filter(p => p.level === 'warning')
  const t = result.summary.total
  const lines = []
  lines.push('# Parity matrix')
  lines.push('')
  lines.push('<!-- GENERATED by `corepack pnpm parity` (scripts/parity) from docs/parity/*.md — do not edit by hand. -->')
  lines.push('')
  lines.push('Every mineflayer 4.39.0 export, bot property, method, event, window-class member and test, with its owner')
  lines.push('unit, status and the test that asserts it. Source fragments: ' +
    result.fragments.map(f => `[\`${f.name}\`](parity/${f.name})`).join(', ') + '.' +
    (reference ? ` Cross-checked against the conformance reference surface (mineflayer ${reference.mineflayer}, ${reference.items.length} items).` : ''))
  lines.push('')
  lines.push(`**${t.total} rows:** ${t.done} done, ${t.adapted} adapted, ${t['n.a.']} n.a., ${t.todo} todo ` +
    `(${pct(t.done + t.adapted + t['n.a.'], t.total)} closed). Problems: ${errors.length} error(s), ${warnings.length} warning(s).`)
  lines.push('')
  lines.push('## Coverage per unit')
  lines.push('')
  lines.push('Rows are counted for the last unit of the owner chain (`U4 → U5` counts for U5).')
  lines.push('')
  lines.push(summaryTable('unit', result.summary.byUnit, byUnit))
  lines.push('')
  lines.push('## Coverage per kind')
  lines.push('')
  lines.push(summaryTable('kind', result.summary.byCategory, byCategory))
  lines.push('')
  lines.push('## Problems')
  lines.push('')
  if (result.problems.length === 0) {
    lines.push('None.')
  } else {
    lines.push(renderTable(['level', 'problem', 'where'], result.problems.map(p => [
      p.level, `${p.code}: ${p.message}`, p.file ? `${p.file}${p.line ? ':' + p.line : ''}` : ''
    ])))
  }
  const fromDir = path.join(repoRoot, 'docs/parity')
  for (const cat of byCategory([...new Set(result.rows.map(r => r.category))])) {
    const rows = result.rows.filter(r => r.category === cat)
    lines.push('')
    lines.push(`## ${CATEGORY_TITLES[cat] ?? cat}`)
    lines.push('')
    lines.push(renderTable(['item', 'kind', 'owner', 'status', 'asserting test', 'notes'], rows.map(r => {
      const notes = [r.notes, r.excluded ? `not in the reference surface: ${r.excluded}` : '', r.source !== 'U0-seed.md' ? `from ${r.source}` : '']
        .filter(Boolean).join('; ')
      return [r.item, r.kind, r.owner, r.status, relinkCell(r.test, fromDir, outDir), relinkCell(notes, fromDir, outDir)]
    })))
  }
  lines.push('')
  return lines.join('\n')
}

/** Shift markdown headings down by `n` levels (outside code fences). */
function demoteHeadings (text, n) {
  let fence = false
  return text.split('\n').map(line => {
    if (/^\s*(```|~~~)/.test(line)) fence = !fence
    if (fence) return line
    return line.replace(/^(#{1,6})(\s)/, (m, h, s) => '#'.repeat(Math.min(6, h.length + n)) + s)
  }).join('\n')
}

/**
 * @param {ReturnType<import('./assemble').assemble>} result
 * @param {{ repoRoot: string, outDir: string }} opts
 */
function renderDifferences (result, { repoRoot, outDir }) {
  const lines = []
  lines.push('# Java ↔ Bedrock differences')
  lines.push('')
  lines.push('<!-- GENERATED by `corepack pnpm parity` (scripts/parity) from docs/differences/*.md — do not edit by hand. -->')
  lines.push('')
  lines.push('The only allowed deviations of mineflayer-bedrock from mineflayer are inherent Java/Bedrock differences;')
  lines.push('each unit documents its own in `docs/differences/<unit>.md` (format: [`differences/README.md`](differences/README.md)).')
  lines.push('`adapted` and `n.a.` rows of the [parity matrix](parity.md) link the entries below.')
  lines.push('')
  if (result.differences.length === 0) {
    lines.push('No unit has documented a difference yet.')
    lines.push('')
    return lines.join('\n')
  }
  const referencedBy = new Map()
  for (const row of result.rows) {
    for (const m of `${row.test} ${row.notes}`.matchAll(DIFF_LINK_RE)) {
      const k = `${m[1]}#${m[2] ?? ''}`
      if (!referencedBy.has(k)) referencedBy.set(k, [])
      referencedBy.get(k).push(row.item)
    }
  }
  lines.push(renderTable(['unit', 'fragment', 'entries', 'parity rows linking it'], result.differences.map(d => {
    const rows = [...referencedBy.entries()].filter(([k]) => k.startsWith(d.name + '#')).flatMap(([, v]) => v)
    const entries = (d.text.match(/^###\s/gm) || []).length
    return [d.unit ?? '?', `[\`${d.name}\`](differences/${d.name})`, String(entries), String(rows.length)]
  })))
  const fromDir = path.join(repoRoot, 'docs/differences')
  for (const d of result.differences) {
    lines.push('')
    lines.push(`## ${d.unit ?? d.name}`)
    lines.push('')
    lines.push(`<!-- from docs/differences/${d.name} -->`)
    lines.push(relinkCell(demoteHeadings(d.text.replace(/^#\s+.*\n+/, ''), 1).trim(), fromDir, outDir))
  }
  lines.push('')
  return lines.join('\n')
}

module.exports = { renderParity, renderDifferences, relinkCell, demoteHeadings, unitOrder, CATEGORY_ORDER }
